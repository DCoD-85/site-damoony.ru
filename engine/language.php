<?PHP

class language {
	# --- refs ---
	public \main $main;

	# --- state ---
	public string $language = 'ru-ru';
	public array  $strings = [ ];
	public array  $strings_tosave = [ ];

	# --- methods ---
	public function __construct ( \main $main ) {
		$this->main = $main;

		$detected = $main->main_settings->get( 'language' ) ?? 'ru-ru';
		$this->language = $detected;
	}

	public function load ( ) : self {
		# перечитать язык — URL/куки могли обновиться в main_settings::init()
		$this->language = $this->main->main_settings->get( 'language' ) ?? 'ru-ru';

		# 1. общий файл (fallback)
		$common = $this->parser( $this->path( $this->language , false ) );

		# 2. доменный — перекрывает общий
		$domain = $this->parser( $this->path( $this->language , true ) );

		$this->strings = array_merge( $common , $domain );

		return $this;
	}

	public function set_language ( string $code ) : self {
		$this->language = $code;

		$common = $this->parser( $this->path( $code , false ) );
		$domain = $this->parser( $this->path( $code , true ) );

		$this->strings = array_merge( $common , $domain );

		return $this;
	}

	public function init ( ) : void {
	}

	public function get ( string $key , array $params = [ ] , string $default = '' ) : string {
		if ( isset( $this->strings[ $key ] ) && $this->strings[ $key ] !== '' ) {
			$text = $this->strings[ $key ];
		} else {
			$text = $default;
			$this->strings_tosave[ $key ] = $default;
		}

		return $params ? vsprintf( $text , $params ) : $text;
	}

	public function savedefaults ( ) : void {
		if ( empty( $this->strings_tosave ) ) return;

		$path = $this->path( 'save' , true );
		$existing = $this->parser( $path );
		$merged = $existing;
		$added = 0;

		foreach ( $this->strings_tosave as $key => $value ) {
			if ( isset( $this->strings[ $key ] ) && $this->strings[ $key ] !== '' ) continue;
			if ( isset( $existing[ $key ] ) ) continue;

			$merged[ $key ] = $value;
			$added++;
		}

		if ( $added === 0 ) return;

		ksort( $merged );

		$buffer = "# Auto-generated by language module. Do not edit.\n";
		$buffer .= "# Domain: " . ( $this->main->main_settings->domain_real_name ?? '—' ) . "\n";
		$buffer .= "# Copy missing keys to {$this->language}.inc and translate them.\n";
		$buffer .= "# Missing: " . count( $merged ) . " keys (last update: " . date( 'Y-m-d H:i:s' ) . ")\n\n";

		foreach ( $merged as $key => $value ) {
			$buffer .= $key . "\n";
			$lines = explode( "\n" , (string) $value );
			foreach ( $lines as $line ) {
				$buffer .= "\t" . $line . "\n";
			}
		}

		# каталог может не существовать — создать
		$dir = dirname( $path );
		if ( ! is_dir( $dir ) ) @mkdir( $dir , 0755 , true );

		file_put_contents( $path , $buffer );
	}

	public function current ( ) : string {
		return $this->language;
	}

	# ===============================================================
	#   INTERNAL
	# ===============================================================

	# $domain = false → language/<name>.inc          (общий)
	# $domain = true  → language/domains/<domain>/<name>.inc
	# 'save'          → save.txt.inc
	private function path ( string $name , bool $domain = false ) : string {
		$dir = dirname( __DIR__ ) . DS . 'language';

		if ( $domain ) {
			$domain_name = $this->main->main_settings->domain_real_name ?? '';
			if ( $domain_name !== '' ) {
				$domain_dir = $dir . DS . 'domains' . DS . $domain_name;
				if ( $name === 'save' ) {
					return $domain_dir . DS . 'save.txt.inc';
				}
				return $domain_dir . DS . $name . '.inc';
			}
		}

		if ( $name === 'save' ) {
			return $dir . DS . 'save.txt.inc';
		}

		return $dir . DS . $name . '.inc';
	}

	private function parser ( string $path ) : array {
		if ( ! is_file( $path ) ) return [ ];

		$lines = file( $path , FILE_IGNORE_NEW_LINES );
		if ( $lines === false ) return [ ];

		$result = [ ];
		$key = null;
		$value = [ ];

		foreach ( $lines as $line ) {
			if ( $line === '' ) continue;
			if ( $line[ 0 ] === '#' ) continue;

			if ( $line[ 0 ] === "\t" ) {
				if ( $key !== null ) {
					$value[ ] = substr( $line , 1 );
				}
				continue;
			}

			if ( $key !== null ) {
				$result[ $key ] = trim( implode( "\n" , $value ) );
			}
			$key = trim( $line );
			$value = [ ];
		}

		if ( $key !== null ) {
			$result[ $key ] = trim( implode( "\n" , $value ) );
		}

		return $result;
	}
}